import assert from 'node:assert/strict';
import * as THREE from 'three';
import {Culler} from '../src/perf.js';
const root=new THREE.Group(),mesh=new THREE.InstancedMesh(new THREE.BoxGeometry(1,1,1),new THREE.MeshBasicMaterial(),7);
for(let i=0;i<7;i++)mesh.setMatrixAt(i,new THREE.Matrix4().makeTranslation((i-3)*200,0,0));
root.add(mesh);const culler=new Culler(root);culler.k=100;
culler.update(new THREE.Vector3(-200,0,0));assert.equal(mesh.count,1);
const first=mesh.instanceMatrix.version;
culler.update(new THREE.Vector3(0,0,0));assert.equal(mesh.count,1);
assert(mesh.instanceMatrix.version>first,'Changed membership must upload even when visible count stays equal');
const matrix=new THREE.Matrix4();mesh.getMatrixAt(0,matrix);assert.equal(matrix.elements[12],0);
const unchanged=mesh.instanceMatrix.version;culler.update(new THREE.Vector3(0,0,0));
assert.equal(mesh.instanceMatrix.version,unchanged,'Unchanged sets avoid repeated uploads');
culler.update(new THREE.Vector3(10000,0,0));assert.equal(mesh.count,0);
culler.update(new THREE.Vector3(200,0,0));assert.equal(mesh.count,1);mesh.getMatrixAt(0,matrix);assert.equal(matrix.elements[12],200);
console.log('PASS: same-count instance swaps upload correctly, unchanged sets stay quiet, culling and re-entry work.');
const managed=new THREE.Mesh(new THREE.BoxGeometry(),new THREE.MeshBasicMaterial());
managed.userData.sceneryLodManaged=true;managed.visible=false;root.add(managed);
const managedCuller=new Culler(root);managedCuller.update(new THREE.Vector3());
assert.equal(managed.visible,false,'LOD-owned visibility must not be overwritten by distance culling');
assert(!managedCuller.items.some(it=>it.o===managed));
console.log('PASS: scenery LOD visibility is owned by its controller.');
